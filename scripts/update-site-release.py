#!/usr/bin/env python3
"""Refresh the static website's public release metadata and local Android QR.

Requires qrcode==8.2 (SVG output, no Pillow). API errors fail without replacing
an existing snapshot. No public stable release is a valid, explicit empty state.
"""
import json
import os
import re
import sys
from pathlib import Path
from urllib.error import HTTPError
from urllib.request import Request, urlopen

REPO = "DigholeNet/vault"
BASE = f"https://github.com/{REPO}"
SITE = Path(__file__).resolve().parents[1] / "website"


def request_json(endpoint):
    headers = {"Accept": "application/vnd.github+json", "User-Agent": "vault-pages-release-sync"}
    token = os.environ.get("GITHUB_TOKEN")
    if token:
        headers["Authorization"] = f"Bearer {token}"
    with urlopen(Request(f"https://api.github.com/repos/{REPO}/{endpoint}", headers=headers), timeout=30) as response:
        return json.load(response)


def release_snapshot(release):
    result = {"version": None, "published": None, "url": f"{BASE}/releases", "assets": {}}
    if not release or release.get("draft") or release.get("prerelease"):
        return result
    tag = release["tag_name"]
    url = release["html_url"]
    if not url.startswith(f"{BASE}/releases/tag/"):
        raise ValueError("Unexpected release URL")
    result.update(version=tag, published=release["published_at"][:10], url=url)
    patterns = {
        "android": r"vault-android-v.+\.apk",
        "macos": r"Vault-macOS-v.+\.zip",
        "edge-amd64": r"edge-v.+-amd64\.deb",
        "edge-arm64": r"edge-v.+-arm64\.deb",
        "edge-binary-amd64": r"edge-v.+-amd64\.tar\.gz",
        "edge-binary-arm64": r"edge-v.+-arm64\.tar\.gz",
        "supernode-amd64": r"supernode-v.+-amd64\.deb",
        "supernode-arm64": r"supernode-v.+-arm64\.deb",
        "supernode-binary-amd64": r"supernode-v.+-amd64\.tar\.gz",
        "supernode-binary-arm64": r"supernode-v.+-arm64\.tar\.gz",
    }
    for asset in release.get("assets", []):
        for platform, pattern in patterns.items():
            if re.fullmatch(pattern, asset["name"]):
                address = asset["browser_download_url"]
                if not address.startswith(f"{BASE}/releases/download/"):
                    raise ValueError("Unexpected asset URL")
                if platform in result["assets"]:
                    raise ValueError(f"Ambiguous asset for {platform}")
                result["assets"][platform] = address
    return result


def write_snapshot(snapshot):
    import qrcode
    import qrcode.image.svg

    target = snapshot["assets"].get("android", snapshot["url"])
    qr = qrcode.QRCode(error_correction=qrcode.constants.ERROR_CORRECT_M, border=4)
    qr.add_data(target)
    qr.make(fit=True)
    svg = qr.make_image(image_factory=qrcode.image.svg.SvgPathFillImage).to_string()
    metadata = "// Generated by scripts/update-site-release.py. Do not edit manually.\nwindow.vaultRelease = " + json.dumps(snapshot, ensure_ascii=True, indent=2) + ";\n"
    # Complete all computation first; a failed API request never clears old data.
    (SITE / "assets/android-release-qr.svg").write_bytes(svg)
    (SITE / "release-data.js").write_text(metadata)
    print(f"Website release snapshot: {snapshot['version'] or 'no stable release'}; {len(snapshot['assets'])} assets")


def main():
    try:
        release = request_json("releases/latest")
    except HTTPError as error:
        if error.code != 404:
            raise
        # A private/missing repo also returns 404. Verify access before treating
        # an absent latest release as an empty published-release state.
        request_json("releases?per_page=1")
        release = None
    write_snapshot(release_snapshot(release))


if __name__ == "__main__":
    try:
        main()
    except Exception as error:
        print(f"Release sync failed: {type(error).__name__}: {error}", file=sys.stderr)
        sys.exit(1)
